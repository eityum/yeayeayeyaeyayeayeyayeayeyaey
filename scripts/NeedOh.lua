btn("BUILD BALL", 10, 32, 260, 28, Color3.fromRGB(50, 200, 50)).MouseButton1Click:Connect(function()
    if buildDebounce then return end
    buildDebounce = true
    teardownBall()

    local myPlate = getMyPlate()
    if not myPlate then
        stat.Text = "No plate found"
        buildDebounce = false
        return
    end
    plateBounds = findMyPlateBounds(myPlate)
    if not plateBounds then
        stat.Text = "No plate part"
        buildDebounce = false
        return
    end

    local activeParts = myPlate:FindFirstChild("ActiveParts")
    if not activeParts then
        stat.Text = "No ActiveParts"
        buildDebounce = false
        return
    end

    rebuildBall()
    local fp = {}
    for _, p in pairs(activeParts:GetDescendants()) do
        if p:IsA("BasePart") and isPartSafe(p) and p.Transparency < 0.5 then
            table.insert(fp, p)
        end
    end
    if #fp == 0 then
        stat.Text = "No parts"
        buildDebounce = false
        return
    end

    table.sort(fp, function(a, b)
        return (a.Position - root.Position).Magnitude < (b.Position - root.Position).Magnitude
    end)
    for i = 1, math.min(#ballParts, #fp) do
        local p = fp[i]
        table.insert(parts, p)
        partIndex[p] = i
    end
    rayParams.FilterDescendantsInstances = parts
    overlapParams.FilterDescendantsInstances = parts
    stretchRayParams.FilterDescendantsInstances = parts

    ballPos = plateBounds.center + Vector3.new(0, ballRadius * 2, 0)
    lastBallPos = ballPos
    visualRot = CFrame.identity
    ballVelocity = Vector3.zero
    wasGrounded = false

    posBall()
    active = true
    stat.Text = "Ball: " .. #parts .. " parts"

    conn = RS.Heartbeat:Connect(function(dt)
        if not active then return end

        -- Movement: accelerate TOWARD a target horizontal speed, scaled by dt
        local moveWorld = Vector3.new(dirs.Right - dirs.Left, 0, dirs.Forward - dirs.Backward)
        if moveWorld.Magnitude > 0 then
            local desired = moveWorld.Unit * speed
            local blend = math.min(1, dt * accelRate)
            ballVelocity = Vector3.new(
                ballVelocity.X + (desired.X - ballVelocity.X) * blend,
                ballVelocity.Y,
                ballVelocity.Z + (desired.Z - ballVelocity.Z) * blend
            )
        end

        if rotL then
            visualRot = visualRot * CFrame.Angles(0, math.rad(90) * dt, 0)
        end
        if rotR then
            visualRot = visualRot * CFrame.Angles(0, -math.rad(90) * dt, 0)
        end

        ballVelocity = ballVelocity + gravity * dt
        if ballVelocity.Y < -terminalVelocity then
            ballVelocity = Vector3.new(ballVelocity.X, -terminalVelocity, ballVelocity.Z)
        end

        ballPos = ballPos + ballVelocity * dt

        local clamped = clampToPlate(ballPos)
        if clamped ~= ballPos then
            ballPos = clamped
            ballVelocity = Vector3.new(0, ballVelocity.Y, 0)
        end

        -- Ground contact: snap to floor, dent the bottom ONCE per landing (edge-triggered)
        local groundY = getGroundHeight(ballPos)
        local grounded = ballPos.Y - ballRadius <= groundY
        if grounded then
            ballPos = Vector3.new(ballPos.X, groundY + ballRadius, ballPos.Z)
            if ballVelocity.Y < -1 and not wasGrounded then
                local strength = math.min(10, math.max(4, math.abs(ballVelocity.Y) * 0.15) * squishIntensity)
                -- FIX: (0,-radius,0) was a fixed LOCAL point, which only means "world down" while
                -- the ball hasn't rotated. As soon as it rolls (which happens constantly while
                -- moving), local down drifts away from world down and the dent lands on whatever
                -- side used to be the bottom instead of the side that actually hit the ground.
                -- Convert world-down into the ball's current local/object space first.
                local downLocal = visualRot:VectorToObjectSpace(Vector3.new(0, -1, 0)) * ballRadius
                applyLocalDent(downLocal, strength)
            end
            if ballVelocity.Y < 0 then
                ballVelocity = Vector3.new(ballVelocity.X * 0.3, 0, ballVelocity.Z * 0.3)
            end
        end
        wasGrounded = grounded

        --=== TOUCH DETECTOR: check every fragment individually via a spatial overlap query
        -- (GetPartsInPart), which reads the fragment's actual current geometry directly and
        -- doesn't depend on the legacy Touched-event system keeping up with CFrame teleports ===--
        for i, b in ipairs(parts) do
            local isTouchingNow = false
            local touchImpact = 0
            if b and b.Parent then
                local overlaps = WS:GetPartsInPart(b, overlapParams)
                if #overlaps > 0 then
                    isTouchingNow = true
                    local outwardWorld = visualRot:VectorToWorldSpace(ballParts[i].Unit)
                    touchImpact = math.abs(ballVelocity:Dot(outwardWorld))
                end
            end
            if isTouchingNow and not wasTouchingFragment[i] then
                local strength = math.min(10, math.max(4, touchImpact * 0.15) * squishIntensity)
                applyLocalDent(ballParts[i], strength)
            end
            wasTouchingFragment[i] = isTouchingNow
        end

        -- Fast-motion squash: dent the LEADING edge (the point on the sphere facing the
        -- direction of travel), same detector, no separate system needed
        local velMag = ballVelocity.Magnitude
        if velMag > 20 then
            local travelDirWorld = ballVelocity.Unit
            local leadLocal = visualRot:VectorToObjectSpace(travelDirWorld) * ballRadius
            applyLocalDent(leadLocal, math.min(10, velMag * 0.08 * squishIntensity))
        end

        -- Cursor Stretch: while held, raycast from the camera through the mouse position,
        -- restricted to ONLY this ball's fragments (stretchRayParams Include filter). Whichever
        -- fragment is under the cursor gets pulled outward, following the cursor as it moves.
        if stretchMode and stretchHeld then
            local camera = WS.CurrentCamera
            local mouseLoc = UIS:GetMouseLocation()
            if camera then
                local ray = camera:ScreenPointToRay(mouseLoc.X, mouseLoc.Y)
                local hit = WS:Raycast(ray.Origin, ray.Direction * 1000, stretchRayParams)
                if hit and hit.Instance and partIndex[hit.Instance] then
                    local hitIndex = partIndex[hit.Instance]
                    applyLocalStretch(ballParts[hitIndex], math.min(10, 8 * squishIntensity))
                end
            end
        end

        -- Rolling rotation (horizontal only) -- purely visual, never touches ballVelocity/movement
        local deltaPos = ballPos - lastBallPos
        lastBallPos = ballPos
        local horizontalDelta = Vector3.new(deltaPos.X, 0, deltaPos.Z)
        if horizontalDelta.Magnitude > 0.001 then
            local rollAngle = horizontalDelta.Magnitude / 10
            local rollAxis = Vector3.new(0, 1, 0):Cross(horizontalDelta.Unit)
            if rollAxis.Magnitude > 0.001 then
                visualRot = visualRot * CFrame.fromAxisAngle(rollAxis.Unit, rollAngle)
            end
        end

        -- Spring + decay every point's dent/bulge/stretch toward its target
        for i = 1, #ballParts do
            localDentTarget[i] = localDentTarget[i] * math.max(0, 1 - dt * squishDecay)
            localDentAmount[i] = localDentAmount[i] + (localDentTarget[i] - localDentAmount[i]) * dt * squishSpringSpeed
            if localDentAmount[i] < 0.05 then
                localDentAmount[i] = 0
                localDentTarget[i] = 0
            end

            localBulgeTarget[i] = localBulgeTarget[i] * math.max(0, 1 - dt * squishDecay)
            localBulgeAmount[i] = localBulgeAmount[i] + (localBulgeTarget[i] - localBulgeAmount[i]) * dt * squishSpringSpeed
            if localBulgeAmount[i] < 0.05 then
                localBulgeAmount[i] = 0
                localBulgeTarget[i] = 0
            end

            -- Stretch decays slower than dent/bulge by default so a "grabbed" point holds its
            -- shape for a moment after release instead of snapping back instantly
            localStretchTarget[i] = localStretchTarget[i] * math.max(0, 1 - dt * (squishDecay * 0.5))
            localStretchAmount[i] = localStretchAmount[i] + (localStretchTarget[i] - localStretchAmount[i]) * dt * squishSpringSpeed
            if localStretchAmount[i] < 0.05 then
                localStretchAmount[i] = 0
                localStretchTarget[i] = 0
            end
        end

        ballVelocity = Vector3.new(
            ballVelocity.X * (1 - dt * physicsDrag),
            ballVelocity.Y,
            ballVelocity.Z * (1 - dt * physicsDrag)
        )

        posBall()
    end)

    buildDebounce = false
end)

