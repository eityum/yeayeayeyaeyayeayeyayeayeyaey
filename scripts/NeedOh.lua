posBall = function()
    if not active then return end
    for i = 1, #parts do
        local b = parts[i]
        local d = ballParts[i]
        if b and b.Parent and d then
            for _, v in pairs(b:GetChildren()) do
                if v:IsA("BodyMover") then
                    v:Destroy()
                end
            end
            b.RotVelocity = Vector3.zero
            b.CanCollide = false
            b.Anchored = false

            -- Net radial offset: dent pulls the point IN toward center, bulge pushes it OUT,
            -- and (FIX) stretch now also pushes it OUT — this was computed every frame but
            -- never actually applied to fragment positions before, so cursor-stretch had zero
            -- visible effect no matter how hard you pulled.
            local netRadial = (localBulgeAmount[i] * bulgeDepth)
                - (localDentAmount[i] * dentDepth)
                + (localStretchAmount[i] * stretchDepth)
            local pos = d + d.Unit * netRadial

            b.CFrame = CFrame.new(ballPos) * visualRot * CFrame.new(pos)
        end
    end
end

