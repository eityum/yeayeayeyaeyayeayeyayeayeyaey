local ballDirs = {} -- unit-sphere direction for each lattice point; only regenerated by
                     -- rebuildBall(), so the point count only ever changes on a full rebuild

local function rebuildBall()
    ballParts = {}
    ballDirs = {}
    localDentTarget, localDentAmount = {}, {}
    localBulgeTarget, localBulgeAmount = {}, {}
    localStretchTarget, localStretchAmount = {}, {}
    wasTouchingFragment = {}

    -- Point count scales with radius instead of block Size scaling with radius: surface area
    -- grows with r^2, so we scale linear resolution with r to keep spacing between grabbed
    -- blocks roughly constant. This only works as well as how many real blocks are sitting on
    -- your plate — a bigger ball needs proportionally more placed blocks to stay gap-free;
    -- past that it'll just leave some lattice points unfilled (same as running low on parts).
    local resolution = math.clamp(math.floor(10 * (ballRadius / baseRadius) + 0.5), 4, 20)
    for lat = 0, resolution do
        local theta = (math.pi * lat) / resolution
        local sinTheta = math.sin(theta)
        local cosTheta = math.cos(theta)
        local actualPoints = math.max(3, math.floor(resolution * 2 * sinTheta))
        for lon = 0, actualPoints do
            local phi = (2 * math.pi * lon) / actualPoints
            local dir = Vector3.new(
                sinTheta * math.cos(phi),
                cosTheta,
                sinTheta * math.sin(phi)
            )
            table.insert(ballDirs, dir)
            table.insert(ballParts, dir * ballRadius)
            local idx = #ballParts
            localDentTarget[idx] = 0
            localDentAmount[idx] = 0
            localBulgeTarget[idx] = 0
            localBulgeAmount[idx] = 0
            localStretchTarget[idx] = 0
            localStretchAmount[idx] = 0
            wasTouchingFragment[idx] = false
        end
    end
end
rebuildBall()

-- Rescales the EXISTING lattice to the current ballRadius without touching point count, so it's
-- safe to call on a live, already-built ball (fragment<->index bindings stay valid — same number
-- of points, just spaced differently). Use this for live size tweaks; use rebuildBall() only when
-- actually regathering parts (BUILD BALL), since that's the only time point count may change.
local function rescaleBallRadius()
    for j = 1, #ballDirs do
        ballParts[j] = ballDirs[j] * ballRadius
    end
end

-- Applies a dent centered at `centerLocal` (a point in the ball's own local space, e.g. one
-- of the ballParts entries) with the given `strength` (0-10ish). Every nearby point gets a
-- dent contribution based on distance falloff, plus a smaller rim-bulge contribution.
local function applyLocalDent(centerLocal, strength)
    for j = 1, #ballParts do
        local dist = (ballParts[j] - centerLocal).Magnitude
        if dist < dentRadius then
            local r = dist / dentRadius
            local dentFalloff = (1 - r) * (1 - r)                                  -- peaks at the contact point
            local bulgeFalloff = math.max(0, 1 - math.abs(r - 0.75) / 0.35) * 0.4  -- small ring around r≈0.75

            local dentVal = strength * dentFalloff
            local bulgeVal = strength * bulgeFalloff
            if dentVal > localDentTarget[j] then localDentTarget[j] = dentVal end
            if bulgeVal > localBulgeTarget[j] then localBulgeTarget[j] = bulgeVal end
        end
    end
end

-- Same falloff shape as applyLocalDent, but pulls points OUTWARD instead of in. Used for the
-- cursor-stretch feature: grab a point on the ball's surface and drag it out like taffy.
local function applyLocalStretch(centerLocal, strength)
    for j = 1, #ballParts do
        local dist = (ballParts[j] - centerLocal).Magnitude
        if dist < dentRadius then
            local r = dist / dentRadius
            local falloff = (1 - r) * (1 - r)
            local val = strength * falloff
            if val > localStretchTarget[j] then localStretchTarget[j] = val end
        end
    end
end

local function isPartSafe(p)
    if p.Anchored then return false end
    for _, plr in pairs(PS:GetPlayers()) do
        if plr.Character and p:IsDescendantOf(plr.Character) then return false end
    end
    if next(p:GetJoints()) ~= nil then return false end
    for _, c in pairs(p:GetChildren()) do
        if c:IsA("JointInstance") or c:IsA("Constraint") then return false end
    end
    return true
end

local function getMyPlate()
    local Plates = WS:FindFirstChild("Plates")
    if not Plates then return nil end
    for _, plate in pairs(Plates:GetChildren()) do
        local owner = plate:FindFirstChild("Owner")
        if owner and owner.Value == LPlayer then return plate end
    end
    return nil
end

local function findMyPlateBounds(plate)
    local platePart = plate and plate:FindFirstChild("Plate")
    if not (platePart and platePart:IsA("BasePart")) then return nil end
    local size = platePart.Size
    local pos = platePart.Position
    return {
        minX = pos.X - size.X / 2,
        maxX = pos.X + size.X / 2,
        minZ = pos.Z - size.Z / 2,
        maxZ = pos.Z + size.Z / 2,
        center = pos
    }
end

local function clampToPlate(pos)
    if not plateBounds then return pos end
    local radius = ballRadius + 2
    return Vector3.new(
        math.clamp(pos.X, plateBounds.minX + radius, plateBounds.maxX - radius),
        pos.Y,
        math.clamp(pos.Z, plateBounds.minZ + radius, plateBounds.maxZ - radius)
    )
end

local function getGroundHeight(pos)
    local hit = WS:Raycast(pos + Vector3.new(0, 50, 0), Vector3.new(0, -300, 0), rayParams)
    if hit then return hit.Position.Y end
    return pos.Y - 50
end

