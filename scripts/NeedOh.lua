--=========================================================================
-- TOUCH DETECTOR: per-point localized squish system.
-- Instead of one "squish axis" for the whole ball, every fragment of the
-- ball is checked individually via a spatial overlap query (GetPartsInPart),
-- which is far more reliable than the legacy GetTouchingParts/Touched event
-- system for parts whose position is set directly via CFrame every frame
-- rather than moved by the physics engine. Any fragment that's actually
-- overlapping something dents INWARD right at that spot, with a soft
-- falloff to nearby fragments and a small outward rim bulge for volume.
-- Ground landings, wall/object contact, fast-motion squash, the manual
-- squish buttons, AND cursor stretch are all just different callers of the
-- same applyLocalDent()/applyLocalStretch() functions below.
--=========================================================================
local squishIntensity = 1       -- 0 = rigid, 1 = default, up to 3 = extremely squishy (scales strength + depth)
local dentRadius = 9            -- studs; how far a dent's influence spreads across the ball's surface
local dentDepth = 0.6           -- studs of inward dent per unit of squish strength (strength maxes at 10)
local bulgeDepth = 0.25         -- studs of outward rim bulge per unit of squish strength
local squishSpringSpeed = 6     -- how fast the visible dent/stretch springs toward its target each frame
local squishDecay = 3           -- how fast a target fades on its own once nothing is re-triggering it

local localDentTarget, localDentAmount = {}, {}
local localBulgeTarget, localBulgeAmount = {}, {}
local localStretchTarget, localStretchAmount = {}, {}
local wasTouchingFragment = {}  -- per-fragment edge-trigger so resting contact doesn't stay pinned forever
local wasGrounded = false

-- Updates ballRadius and keeps dentRadius proportional to it (dentRadius was tuned as
-- 0.9x a 10-stud ball, so we preserve that ratio at any size). Clamped to a sane range.
local function applyRadius(r)
    ballRadius = math.clamp(r, 3, 30)
    dentRadius = ballRadius * 0.9
end

